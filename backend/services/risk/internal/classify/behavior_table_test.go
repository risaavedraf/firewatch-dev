// goldenBehaviorTableHash is sha256(goldenBehaviorTable). Freezing both the text
// and its hash means editing the literal without updating the hash fails too, so
// a lock cannot be quietly rewritten.
const goldenBehaviorTableHash = "5403ebfdf2078723133c9fcc3ac040ed8e1169d3408904662ef910a8c50cfc27"

func TestAcademicRuleV1BehaviorTableIsFrozen(t *testing.T) {
	generated, err := behaviorTableText(t.Context(), DefaultAcademicRuleV1Params())
	if err != nil {
		t.Fatalf("building the behaviour table failed: %v", err)
	}
	if generated != goldenBehaviorTable {
		t.Fatalf("academic-rule-v1 behaviour changed; a frozen entry moved:\n%s", behaviorTableDifference(goldenBehaviorTable, generated))
	}
}

func TestGoldenBehaviorTableHashPinsTheLiteral(t *testing.T) {
	sum := sha256.Sum256([]byte(goldenBehaviorTable))
	if got := hex.EncodeToString(sum[:]); got != goldenBehaviorTableHash {
		t.Fatalf("goldenBehaviorTableHash = %q, want sha256(goldenBehaviorTable) = %q", goldenBehaviorTableHash, got)
	}

	generated, err := behaviorTableText(t.Context(), DefaultAcademicRuleV1Params())
	if err != nil {
		t.Fatalf("building the behaviour table failed: %v", err)
	}
	generatedSum := sha256.Sum256([]byte(generated))
	if got := hex.EncodeToString(generatedSum[:]); got != goldenBehaviorTableHash {
		t.Fatalf("sha256(generated behaviour table) = %q, want the frozen %q", got, goldenBehaviorTableHash)
	}
	t.Logf("behaviour table entries: %d lines, hash %s", strings.Count(goldenBehaviorTable, "\n"), goldenBehaviorTableHash)
}

// TestBehaviorTableAnchorsMirrorTheFrozenDefaults keeps the hand-written probe
// anchors aligned with DefaultAcademicRuleV1Params, so the labels at-low,
// at-high and exactly-6h cannot become lies. It is an anchor-alignment guard, not
// a second parameter lock: TestAcademicRuleV1ParametersAreFrozen is the lock.
func TestBehaviorTableAnchorsMirrorTheFrozenDefaults(t *testing.T) {
	anchors := defaultBehaviorAnchors()
	defaults := DefaultAcademicRuleV1Params()

	cases := []struct {
		name string
		got  float64
		want float64
	}{
		{"temperature-low", anchors.temperatureLow, defaults.TemperatureLowC},
		{"temperature-high", anchors.temperatureHigh, defaults.TemperatureHighC},
		{"humidity-low", anchors.humidityLow, defaults.HumidityDryPct},
		{"humidity-high", anchors.humidityHigh, defaults.HumidityWetPct},
		{"wind-low", anchors.windLow, defaults.WindLowKmh},
		{"wind-high", anchors.windHigh, defaults.WindHighKmh},
		{"vegetation-low", anchors.vegetationLow, defaults.VegetationSparsePct},
		{"vegetation-high", anchors.vegetationHigh, defaults.VegetationDensePct},
		{"fires-low", anchors.firesLow, defaults.HistoricalFiresLow},
		{"fires-high", anchors.firesHigh, defaults.HistoricalFiresHigh},
	}
	for _, testCase := range cases {
		if testCase.got != testCase.want {
			t.Errorf("behaviour-table anchor %s = %v, want the frozen default %v", testCase.name, testCase.got, testCase.want)
		}
	}

	if want := time.Duration(defaults.MaxStalenessSeconds) * time.Second; anchors.staleness != want {
		t.Errorf("behaviour-table staleness anchor = %v, want the frozen default %v", anchors.staleness, want)
	}
}
