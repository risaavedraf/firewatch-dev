// This file is the BEHAVIOUR lock of academic-rule-v1.
//
// The parameter lock (Params, AcademicRuleV1ParamsHash,
// TestAcademicRuleV1ParametersAreFrozen) freezes the FIELDS of Params, and the
// structural guard in params_test.go rejects behaviour numbers spelled outside
// that object. Neither can see a mutation that introduces no literal at all: an
// adversarial review changed `case score < p.BandBajoMax` into
// `case score <= p.BandBajoMax`, the whole suite stayed green, and the level at
// exactly 0.34 silently moved from medio to bajo. The only honest response is a
// dense, frozen behaviour table: the effective outputs of the rule, recorded as
// bytes and compared on every run.
//
// Golden-behaviour discipline: the literal below is the source of truth and it
// is never regenerated by code. There is deliberately no `-update` flag, no
// os.WriteFile, no go:generate directive and no other write path anywhere in
// this package. When a future change is intentional, the author edits the
// literal by hand, verifies the new entries, computes the new
// goldenBehaviorTableHash by hand (sha256 of the literal), and updates both in
// the same commit - so the diff of the lock is a reviewed, human artifact.
//
// The serialization is deterministic: floats are written with
// strconv.FormatFloat(v, 'g', -1, 64), which is a bit-exact round trip in Go; the
// entries are fixed-order, one per line, with no maps and no locale so a
// deliberate change produces a readable diff.

// behaviorFloat is the one float encoding of the table: the shortest
// representation that round-trips to the exact same 64-bit value.
func behaviorFloat(value float64) string {
	return strconv.FormatFloat(value, 'g', -1, 64)
}

// levelScoreProbe is one score fed to levelFor for table (a).
type levelScoreProbe struct {
	group string
	score float64
}

// levelScoreProbes is the frozen score set of table (a). It exists to catch the
// literal-free operator mutation that no static guard can see, so it contains
// every boundary EXACTLY, its immediate neighbours, and the surrounding regions:
//
//   - both band boundaries exactly (BandBajoMax, BandMedioMax);
//   - one ulp below and one ulp above each boundary;
//   - 0 and 1 exactly, the edges of the unit interval;
//   - values outside [0, 1] (-0.001, 1.001, -1, 2), which must not be clamped;
//   - a 0.01 grid over [0, 1] inclusive (101 entries);
//   - the midpoint of each band;
//   - NaN, +Inf and -Inf, whose result is fixed here on purpose rather than left
//     undefined: levelFor is a total function and the table records what it does.
//
// The boundary entries are what rule out `<` turned into `<=`: with `<` the
// boundary score belongs to the UPPER band, with `<=` it would fall into the
// lower one, so flipping the operator moves exactly these four lines.
func levelScoreProbes(params Params) []levelScoreProbe {
	bajo := params.BandBajoMax
	medio := params.BandMedioMax

	probes := []levelScoreProbe{
		{"band-boundary", bajo},
		{"band-boundary", medio},
		{"band-boundary-ulp-below", math.Nextafter(bajo, math.Inf(-1))},
		{"band-boundary-ulp-above", math.Nextafter(bajo, math.Inf(1))},
		{"band-boundary-ulp-below", math.Nextafter(medio, math.Inf(-1))},
		{"band-boundary-ulp-above", math.Nextafter(medio, math.Inf(1))},
		{"unit-interval-edge", 0},
		{"unit-interval-edge", 1},
		{"outside-unit-interval", -0.001},
		{"outside-unit-interval", 1.001},
		{"outside-unit-interval", -1},
		{"outside-unit-interval", 2},
	}
	for step := 0; step <= 100; step++ {
		probes = append(probes, levelScoreProbe{"grid-0.01", float64(step) / 100})
	}
	probes = append(probes,
		levelScoreProbe{"band-midpoint", bajo / 2},
		levelScoreProbe{"band-midpoint", (bajo + medio) / 2},
		levelScoreProbe{"non-finite", math.NaN()},
		levelScoreProbe{"non-finite", math.Inf(1)},
		levelScoreProbe{"non-finite", math.Inf(-1)},
	)
	return probes
}

// behaviorAnchors are the ABSOLUTE probe anchors of table (b).
//
// They mirror the frozen defaults of DefaultAcademicRuleV1Params and are written
// out by hand on purpose. If the sweeps were computed relative to a threshold,
// they would move with that threshold and a threshold change would be INVISIBLE
// in the table: rising(value, low, high) normalizes away any shift of both
// bounds. Anchored on absolute values, the at-low, just-above-low and at-high
// probes change the moment a threshold does.
//
// TestBehaviorTableAnchorsMirrorTheFrozenDefaults keeps these labels honest, and
// TestAcademicRuleV1ParametersAreFrozen independently pins the parameters
// themselves.
type behaviorAnchors struct {
	temperatureLow  float64
	temperatureHigh float64
	humidityLow     float64
	humidityHigh    float64
	windLow         float64
	windHigh        float64
	vegetationLow   float64
	vegetationHigh  float64
	firesLow        float64
	firesHigh       float64
	staleness       time.Duration
}

func defaultBehaviorAnchors() behaviorAnchors {
	return behaviorAnchors{
		temperatureLow:  15,
		temperatureHigh: 35,
		humidityLow:     20,
		humidityHigh:    60,
		windLow:         10,
		windHigh:        50,
		vegetationLow:   10,
		vegetationHigh:  70,
		firesLow:        0,
		firesHigh:       5,
		staleness:       6 * time.Hour,
	}
}

// featureProbe is one input set of table (b).
type featureProbe struct {
	group    string
	name     string
	features Features
}

// featureProbes is the frozen input set of table (b). For every probe the table
// records the resulting Level and the five factor Contributions.
//
//   - one-variable sweeps from a mid baseline, for each of the five variables, at
//     nine values: below the low threshold, the low threshold EXACTLY,
//     Nextafter(low, +Inf), the quarter/half/three-quarter points, the high
//     threshold EXACTLY, Nextafter(high, -Inf), and above the high threshold. The
//     exact-threshold and ulp-neighbour entries are mandatory: they are what
//     catches an inclusive/exclusive change inside linear and falling, which no
//     literal-based guard can see.
//   - all-low, all-mid, all-high and all-edge probes.
//   - the staleness gate at exactly 6h, 6h+1s and 6h-1s.
//   - five mixed probes combining several variables away from their thresholds.
func featureProbes(anchors behaviorAnchors) []featureProbe {
	mid := probeFeatures(25, 40, 30, 40, 2.5, 0)

	sweeps := []struct {
		variable string
		low      float64
		high     float64
		set      func(*Features, float64)
	}{
		{"temperature", anchors.temperatureLow, anchors.temperatureHigh, func(f *Features, value float64) { f.TemperatureC = Known(value) }},
		{"humidity", anchors.humidityLow, anchors.humidityHigh, func(f *Features, value float64) { f.RelativeHumidityPct = Known(value) }},
		{"wind", anchors.windLow, anchors.windHigh, func(f *Features, value float64) { f.WindSpeedKmh = Known(value) }},
		{"vegetation", anchors.vegetationLow, anchors.vegetationHigh, func(f *Features, value float64) { f.VegetationCoverPct = Known(value) }},
		{"historical-fires", anchors.firesLow, anchors.firesHigh, func(f *Features, value float64) { f.HistoricalFires = Known(value) }},
	}

	points := []struct {
		label string
		value func(low, high float64) float64
	}{
		{"below-low", func(low, high float64) float64 { return low - 1 }},
		{"at-low", func(low, high float64) float64 { return low }},
		{"just-above-low", func(low, high float64) float64 { return math.Nextafter(low, math.Inf(1)) }},
		{"quarter", func(low, high float64) float64 { return low + 0.25*(high-low) }},
		{"half", func(low, high float64) float64 { return low + 0.5*(high-low) }},
		{"three-quarter", func(low, high float64) float64 { return low + 0.75*(high-low) }},
		{"just-below-high", func(low, high float64) float64 { return math.Nextafter(high, math.Inf(-1)) }},
		{"at-high", func(low, high float64) float64 { return high }},
		{"above-high", func(low, high float64) float64 { return high + 1 }},
	}

	var probes []featureProbe
	for _, sweep := range sweeps {
		for _, point := range points {
			features := mid
			sweep.set(&features, point.value(sweep.low, sweep.high))
			probes = append(probes, featureProbe{
				group:    "sweep",
				name:     "sweep-" + sweep.variable + "-" + point.label,
				features: features,
			})
		}
	}

	probes = append(probes,
		featureProbe{"all", "all-low", probeFeatures(10, 90, 5, 5, 0, 0)},
		featureProbe{"all", "all-mid", mid},
		featureProbe{"all", "all-high", probeFeatures(40, 5, 60, 90, 9, 0)},
		// all-edge floors every contribution at once: the low edge of each rising
		// variable and the high edge of the falling one.
		featureProbe{"all", "all-edge", probeFeatures(
			anchors.temperatureLow, anchors.humidityHigh, anchors.windLow,
			anchors.vegetationLow, anchors.firesLow, 0,
		)},

		// The staleness gate. Exactly at the limit the observation is still
		// classified (age > max is strict); one second past it is not.
		featureProbe{"staleness", "stale-exactly-6h", probeFeatures(25, 40, 30, 40, 2.5, anchors.staleness)},
		featureProbe{"staleness", "stale-6h-plus-1s", probeFeatures(25, 40, 30, 40, 2.5, anchors.staleness+time.Second)},
		featureProbe{"staleness", "stale-6h-minus-1s", probeFeatures(25, 40, 30, 40, 2.5, anchors.staleness-time.Second)},

		// Mixed probes: several variables away from every threshold at once, so
		// the weighted sum - not a single clamped contribution - is exercised.
		featureProbe{"mixed", "mixed-warm-dry-windy", probeFeatures(38, 15, 45, 60, 4, 0)},
		featureProbe{"mixed", "mixed-cool-wet-calm", probeFeatures(12, 80, 8, 20, 1, 0)},
		featureProbe{"mixed", "mixed-hot-and-wet", probeFeatures(40, 70, 25, 50, 3, 0)},
		featureProbe{"mixed", "mixed-mild-dense-fuel", probeFeatures(26, 45, 35, 80, 4.5, 0)},
		featureProbe{"mixed", "mixed-cold-dry-sparse", probeFeatures(16, 18, 55, 5, 0.5, 0)},
	)
	return probes
}

// behaviorTableText builds the canonical text serialization of academic-rule-v1's
// behaviour under params: the level for every score in table (a), and the level
// plus the five factor contributions for every probe in table (b).
//
// It is the generator of the frozen literal, not a writer of it: it returns a
// string and nothing in the package ever persists that string. The lock is the
// literal in TestAcademicRuleV1BehaviorTableIsFrozen, which a human edits by
// hand.
func behaviorTableText(ctx context.Context, params Params) (string, error) {
	hash, err := params.Hash()
	if err != nil {
		return "", fmt.Errorf("hash the parameters: %w", err)
	}

	var builder strings.Builder
	builder.WriteString("academic-rule-v1 canonical behaviour table\n")
	builder.WriteString("params_hash=" + hash + "\n")
	builder.WriteString("# section (a): level by score. The band-boundary entries rule out a less-than comparison turned into less-than-or-equal in levelFor.\n")
	for _, probe := range levelScoreProbes(params) {
		fmt.Fprintf(&builder, "a group=%s score=%s level=%s\n", probe.group, behaviorFloat(probe.score), params.levelFor(probe.score))
	}
	builder.WriteString("# section (b): level and factor contributions by features. The at-low/at-high and ulp-neighbour entries rule out an inclusive/exclusive change inside linear and falling.\n")

	rule := newAcademicRuleV1(params)
	for _, probe := range featureProbes(defaultBehaviorAnchors()) {
		assessment, err := rule.Classify(ctx, probe.features)
		if err != nil {
			return "", fmt.Errorf("probe %s: %w", probe.name, err)
		}
		fmt.Fprintf(&builder, "b group=%s probe=%s level=%s", probe.group, probe.name, assessment.Level)
		for _, factor := range assessment.Factors {
			fmt.Fprintf(&builder, " contrib.%s=%s", factor.Name, behaviorFloat(factor.Contribution))
		}
		builder.WriteString("\n")
	}
	return builder.String(), nil
}

// behaviorTableDifference returns the first line where the frozen and the
// generated table differ, so a failure names the single moved entry instead of
// dumping two long strings.
func behaviorTableDifference(want, got string) string {
	wantLines := strings.Split(want, "\n")
	gotLines := strings.Split(got, "\n")
	limit := len(wantLines)
	if len(gotLines) < limit {
		limit = len(gotLines)
	}
	for index := 0; index < limit; index++ {
		if wantLines[index] != gotLines[index] {
			return fmt.Sprintf("line %d:\n  frozen:    %s\n  generated: %s", index+1, wantLines[index], gotLines[index])
		}
	}
	if len(wantLines) != len(gotLines) {
		return fmt.Sprintf("line count differs: frozen %d, generated %d", len(wantLines), len(gotLines))
	}
	return ""
}

